import { ExportSettings, GeneratedHingeData, HingeParams } from '../types/hinge';

export function buildSvgString(
  data: GeneratedHingeData,
  params: HingeParams,
  settings: ExportSettings
): string {
  const { totalWidth, totalHeight, cutPaths, outerBorderPaths, holePaths } = data;
  const unit = settings.unit;
  const unitSuffix = unit === 'inch' ? 'in' : 'mm';
  const scale = unit === 'inch' ? 1 / 25.4 : 1;

  const wDisplay = (totalWidth * scale).toFixed(3);
  const hDisplay = (totalHeight * scale).toFixed(3);

  // Stroke colors for laser cutter layer mapping
  let cutStroke = '#ff0000'; // Default red cut
  let borderStroke = '#000000'; // Black cut
  let holeStroke = '#0000ff'; // Blue cut

  if (settings.colorScheme === 'black-cut') {
    cutStroke = '#000000';
    borderStroke = '#333333';
    holeStroke = '#555555';
  } else if (settings.colorScheme === 'blue-cut') {
    cutStroke = '#0055ff';
    borderStroke = '#ff0000';
    holeStroke = '#00aa00';
  }

  // Laser hairline width: standard is 0.05mm - 0.1mm (or 0.001in)
  const strokeWidth = settings.hairlineWidth;

  let svg = `<?xml version="1.0" encoding="UTF-8" standalone="no"?>
<!-- Generated by KerfBend Living Hinge CAD Designer -->
<!-- Pattern: ${params.pattern} | Orientation: ${params.cutOrientation} | Cut: ${params.cutLength}mm | Bridge: ${params.bridgeSize}mm | Pitch: ${params.lineSpacing}mm -->
<svg xmlns="http://www.w3.org/2000/svg"
     width="${wDisplay}${unitSuffix}"
     height="${hDisplay}${unitSuffix}"
     viewBox="0 0 ${totalWidth} ${totalHeight}"
     version="1.1">
  <title>Living Hinge - ${params.pattern} (${params.cutOrientation})</title>
  <desc>Parametric Living Hinge Pattern for Laser Cutting (${params.cutOrientation} cuts). Cut Lines: ${cutPaths.length}, Total Length: ${data.stats.totalCutLengthMm}mm</desc>

  <!-- Laser Cutting Group: Hinge Slits -->
  <g id="Living_Hinge_Cuts" stroke="${cutStroke}" stroke-width="${strokeWidth}" fill="none" stroke-linecap="round" stroke-linejoin="round">
`;

  for (const cp of cutPaths) {
    if (cp.points.length === 2) {
      svg += `    <line x1="${cp.points[0].x}" y1="${cp.points[0].y}" x2="${cp.points[1].x}" y2="${cp.points[1].y}" />\n`;
    } else if (cp.points.length > 2) {
      let d = `M ${cp.points[0].x} ${cp.points[0].y}`;
      for (let i = 1; i < cp.points.length; i++) {
        d += ` L ${cp.points[i].x} ${cp.points[i].y}`;
      }
      svg += `    <path d="${d}" />\n`;
    }
  }
  svg += `  </g>\n\n`;

  // Outer border if present
  if (settings.includeOuterBorder && outerBorderPaths.length > 0) {
    svg += `  <!-- Outer Perimeter Cut -->\n`;
    svg += `  <g id="Outer_Border" stroke="${borderStroke}" stroke-width="${strokeWidth}" fill="none" stroke-linecap="round" stroke-linejoin="round">\n`;
    for (const op of outerBorderPaths) {
      let d = `M ${op.points[0].x} ${op.points[0].y}`;
      for (let i = 1; i < op.points.length; i++) {
        d += ` L ${op.points[i].x} ${op.points[i].y}`;
      }
      svg += `    <path d="${d} Z" />\n`;
    }
    svg += `  </g>\n\n`;
  }

  // Mounting / Alignment Holes
  if (holePaths.length > 0) {
    svg += `  <!-- Mounting / Alignment Holes -->\n`;
    svg += `  <g id="Mounting_Holes" stroke="${holeStroke}" stroke-width="${strokeWidth}" fill="none">\n`;
    for (const hp of holePaths) {
      if (hp.radius) {
        svg += `    <circle cx="${hp.points[0].x}" cy="${hp.points[0].y}" r="${hp.radius}" />\n`;
      }
    }
    svg += `  </g>\n\n`;
  }

  // Dimension / Annotation layer if requested
  if (settings.includeDimensionsLayer) {
    svg += `  <!-- Dimensions & Information Layer (Do Not Cut / Engrave Only) -->\n`;
    svg += `  <g id="Annotations_Dimensions" stroke="#888888" stroke-width="0.2" fill="#666666" font-family="monospace" font-size="3" text-anchor="middle">\n`;
    svg += `    <text x="${totalWidth / 2}" y="${Math.max(3.5, params.marginTop / 2)}" font-size="3">Hinge: ${params.hingeWidth}mm x ${params.hingeHeight}mm | Cut: ${params.cutLength}mm | Bridge: ${params.bridgeSize}mm | Pitch: ${params.lineSpacing}mm</text>\n`;
    svg += `  </g>\n`;
  }

  svg += `</svg>`;
  return svg;
}

export function downloadSvg(
  data: GeneratedHingeData,
  params: HingeParams,
  settings: ExportSettings
) {
  const svgContent = buildSvgString(data, params, settings);
  const blob = new Blob([svgContent], { type: 'image/svg+xml;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  const fileName = `living-hinge-${params.pattern}-${Math.round(params.hingeWidth)}x${Math.round(params.hingeHeight)}mm.svg`;
  a.download = fileName;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
